// Writes src/land-110m.ts, the basic map's world outline, from Natural Earth's
// 1:110m land polygons (public domain):
//   node scripts/build-land.mjs path/to/ne_110m_land.geojson
// Source: https://github.com/nvkelso/natural-earth-vector/blob/v5.1.2/geojson/ne_110m_land.geojson

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const input = process.argv[2];
if (!input) throw new Error("usage: node scripts/build-land.mjs <ne_110m_land.geojson>");

const geojson = JSON.parse(readFileSync(input, "utf8"));
const rings = [];
for (const { geometry } of geojson.features) {
  const polygons = geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates;
  for (const polygon of polygons) {
    for (const ring of polygon) rings.push(ring.flatMap(([lon, lat]) => [Math.round(lon * 100), Math.round(lat * 100)]));
  }
}

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "land-110m.ts");
writeFileSync(
  out,
  [
    "// Generated by scripts/build-land.mjs from Natural Earth's 1:110m land",
    "// polygons, v5.1.2 (public domain, naturalearthdata.com). Each ring is",
    "// [lon, lat, lon, lat, …] in hundredths of a degree; holes are rings too,",
    "// so fill with the even-odd rule. Do not edit by hand.",
    "export const LAND_110M: readonly (readonly number[])[] = [",
    ...rings.map((r) => `  [${r.join(",")}],`),
    "];",
    "",
  ].join("\n"),
);
console.log(`${out}: ${rings.length} rings, ${rings.reduce((n, r) => n + r.length / 2, 0)} points`);
